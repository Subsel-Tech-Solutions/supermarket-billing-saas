// src/service-worker.js
// Production Service Worker with Workbox for SuperMart POS
// Precaches App Shell so cashier counters remain open and usable even when Wi-Fi drops,
// while strictly enforcing NetworkOnly on all financial / inventory / bill API routes.

import { clientsClaim } from 'workbox-core';
import { ExpirationPlugin } from 'workbox-expiration';
import { precacheAndRoute, createHandlerBoundToURL } from 'workbox-precaching';
import { registerRoute } from 'workbox-routing';
import { StaleWhileRevalidate, CacheFirst, NetworkOnly } from 'workbox-strategies';

clientsClaim();

// Precache all assets generated by webpack build (injected automatically at build time)
precacheAndRoute(self.__WB_MANIFEST || []);

// Set up App Shell style routing for Single Page Application navigation
const fileExtensionRegexp = new RegExp('/[^/?]+\\.[^/]+$');
registerRoute(
  ({ request, url }) => {
    // Return false if this isn't a navigation request
    if (request.mode !== 'navigate') {
      return false;
    }
    // Return false if this is a reserved URL path
    if (url.pathname.startsWith('/_')) {
      return false;
    }
    // Return false if this is an API call
    if (url.pathname.startsWith('/api')) {
      return false;
    }
    // Return false if this looks like a resource URL (has file extension)
    if (url.pathname.match(fileExtensionRegexp)) {
      return false;
    }
    return true;
  },
  createHandlerBoundToURL(process.env.PUBLIC_URL + '/index.html')
);

// ── STRICT POLICY: No Offline API Mutations / Network-Only Routes ───────────
// Any call to /api/* must NEVER be served from cache.
// If offline, it fails immediately to trigger the application's connection monitor.
registerRoute(
  ({ url }) => url.pathname.startsWith('/api/'),
  new NetworkOnly()
);

// ── Static Assets Caching ──────────────────────────────────────────────────
// Cache Google Fonts
registerRoute(
  ({ url }) =>
    url.origin === 'https://fonts.googleapis.com' ||
    url.origin === 'https://fonts.gstatic.com',
  new StaleWhileRevalidate({
    cacheName: 'google-fonts',
  })
);

// Cache images and icons (e.g., logo, product images)
registerRoute(
  ({ request }) => request.destination === 'image',
  new CacheFirst({
    cacheName: 'images',
    plugins: [
      new ExpirationPlugin({
        maxEntries: 100,
        maxAgeSeconds: 30 * 24 * 60 * 60, // 30 days
      }),
    ],
  })
);

// Handle skipWaiting message to allow immediate update when cashier accepts update
self.addEventListener('message', (event) => {
  if (event.data && event.data.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});
